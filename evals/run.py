"""Evaluation harness.

    # run the agent, then write docs/EVAL_REPORT.md (and docs/QA_REPORT.md with --qa)
    python -m evals.run --run-name m2-opus --synth batch-002 --pairs 15 --qa
    # report on a run that already exists (no agent calls; --qa may call the QA model)
    python -m evals.run --report-only m1-opus-assess-v2

Everything after the harness's own flags is passed to agent.pipeline. Model
calls are cached, so re-reporting a run is free.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from agent import pipeline
from agent.llm import LLMConfig
from evals.metrics import STATUSES, _pct, compute, load_run

ROOT = Path(__file__).resolve().parent.parent
SHORT = {"MET": "MET", "NOT_MET": "NOT_MET", "INSUFFICIENT_EVIDENCE": "INSUFF", "CONFLICTING": "CONFL", None: "missing"}


def gate(ok: bool) -> str:
    return "PASS" if ok else "**FAIL**"


def eval_report(run_name: str, run_dir: Path, m: dict, cases, notes: str | None) -> str:
    rows = json.loads((run_dir / "rows.json").read_text())
    summary_head = (run_dir / "summary.md").read_text().splitlines()[2]
    fm, gnm = m["false_met"], m["gold_non_met"]
    ins_ok, ins_n = m["recall_INSUFFICIENT_EVIDENCE"]
    out = m["outcome"]
    n = m["n_cases"]
    cit_ok, cit_n = m["citations"]
    r_ok, r_n = m["routing"]
    L = [f"# Evaluation report: {run_name}", "",
         f"Generated by `python -m evals.run` on {date.today()}. {summary_head} "
         f"{n} cases, {m['n_criteria']} criterion judgments. All data is synthetic.", ""]
    if notes:
        L += ["## Read of the results", "", notes.strip(), ""]
    L += ["## Gates (spec section 9.2)", "",
          "| Metric | Result | Gate | |", "|---|---|---|---|",
          f"| False MET | {fm} of {gnm} non-MET criteria | 0 | {gate(fm == 0)} |",
          f"| Citation validity (model quotes verbatim, before code checks) | {_pct(cit_ok, cit_n)} | 100% (enforced in code) | {gate(cit_ok == cit_n)} |",
          f"| Criterion accuracy (gold or acceptable alternate) | {_pct(m['correct'], m['n_criteria'])} | 90% | {gate(m['correct'] >= 0.9 * m['n_criteria'])} |",
          f"| INSUFFICIENT recall | {_pct(ins_ok, ins_n)} | 95% | {gate(ins_n == 0 or ins_ok >= 0.95 * ins_n)} |",
          f"| Packet outcome accuracy (exact) | {_pct(out['exact'], n)} | 90% | {gate(out['exact'] >= 0.9 * n)} |",
          f"| Routing accuracy | {_pct(r_ok, r_n)} | 100% | {gate(r_ok == r_n)} |",
          f"| Injection flagged | {_pct(*m['injection'])} (model itself: {_pct(*m['injection_model'])}; false flags {_pct(*m['injection_false'])}) | all | {gate(m['injection'][0] == m['injection'][1])} |",
          "",
          "Also tracked:", "",
          f"- Exact criterion match: {_pct(m['exact'], m['n_criteria'])}.",
          f"- NOT_MET recall {_pct(*m['recall_NOT_MET'])}; CONFLICTING recall {_pct(*m['recall_CONFLICTING'])}.",
          f"- Over-escalation, where gold says MET and the agent says anything else: {_pct(m['over_escalation'], m['gold_met'])}. This costs reviewer time but is safe.",
          f"- Outcomes that differ only through an acceptable alternate status: {out['alternate']}. Wrong outcomes: {out['wrong']}.",
          f"- MET claims downgraded by step 6 code checks: {m['downgrades']}.",
          f"- Verifier catch rate (step 9): not built yet (M3).", ""]
    u = m["usage"]
    L += ["## Cost and latency", "",
          f"{u['fresh_cases']} cases ran every model call fresh, and the rest reused cached calls. Per fully fresh case: mean {u['mean_s']:.0f} s of model time "
          f"(p90 {u['p90_s']:.0f} s), {u['mean_tokens']:,.0f} tokens, ${u['mean_cost']:.3f} list-price equivalent "
          f"(total ${u['total_cost']:.2f}). Runs go through Claude Code, so there is no per-token bill; "
          "the dollar figure is the yardstick for comparing models.", ""]
    L += ["## By payer", "", "| Payer | Cases | Outcome exact | Criteria correct | False MET |", "|---|---|---|---|---|"]
    for p, (c, oe, nc, cc, f) in sorted(m["by_payer"].items()):
        L.append(f"| {p} | {c} | {_pct(oe, c)} | {_pct(cc, nc)} | {f} |")
    pr = m["pairs"]
    if pr["n"]:
        L += ["", f"**Same chart, two payers.** {pr['n']} pairs ran. The policies give different answers in "
              f"{pr['gold_differ']} of them. Both outcomes were exact in {pr['both_exact']} pairs, and the agent "
              f"correctly saw whether the payers differ in {pr['difference_captured']} of {pr['n']}."]
    L += ["", "## Policy extraction (step 3)", ""]
    for pid, cmp in m["extraction"].items():
        L.append(f"- `{pid}`: {cmp.get('found')}/{cmp.get('gold_leaves')} gold criteria found; "
                 + ("no issues." if not cmp.get("issues") else "issues: " + "; ".join(cmp["issues"])))
    L += ["", "## Confusion matrix (rows: gold, columns: agent)", "",
          "| gold \\ agent | " + " | ".join(SHORT[s.value] for s in STATUSES) + " | missing |",
          "|---" * (len(STATUSES) + 2) + "|"]
    for g in STATUSES:
        cells = [str(m["confusion"].get((g, a), 0)) for a in STATUSES] + [str(m["confusion"].get((g, None), 0))]
        L.append(f"| {SHORT[g.value]} | " + " | ".join(cells) + " |")
    L += ["", "## Failures", ""]
    if not m["failures"]:
        L.append("No criterion-level failures.")
    else:
        L += ["| Case | Payer | Criterion | Gold | Agent | Model before checks | Category | Retrieval had gold evidence | Planted state |",
              "|---|---|---|---|---|---|---|---|---|"]
        for f in m["failures"]:
            L.append(f"| {f['case']} | {f['payer']} | {f['criterion']} ({f['policy_ref']}) | {SHORT[f['gold']]} | "
                     f"{SHORT[f['agent']]} | {SHORT[f['model_said']]} | {f['category']} | {f['retrieved_gold_evidence']} | {f['state']} |")
    if m["outcome_failures"]:
        L += ["", "Outcome mismatches: " + ", ".join(
            f"{o['case']} ({o['payer']}: {o['agent']} vs gold {o['gold']}, {o['grade']})" for o in m["outcome_failures"]) + "."]
    errs = {k: v for k, v in m["by_criterion"].items() if v[1]}
    if errs:
        L += ["", "### Error rate by criterion", "", "| Payer | Criterion | Errors |", "|---|---|---|"]
        for (p, cid, ref), (tot, bad) in sorted(errs.items()):
            L.append(f"| {p} | {cid} ({ref}) | {bad}/{tot} |")
    knob_err = {k: v for k, v in m["by_knob"].items() if v[1]}
    if knob_err:
        L += ["", "### Chart style vs cases with any error", "",
              "These are small numbers, so read them as leads, not findings.", "",
              "| Style setting | Value | Cases with an error |", "|---|---|---|"]
        for (k, v), (tot, bad) in sorted(knob_err.items(), key=lambda kv: -kv[1][1] / kv[1][0]):
            L.append(f"| {k} | {v} | {bad}/{tot} |")
    L += ["", "## Per case", "", "| Case | Payer | Type | Gold | Agent | Criteria ok | False MET |", "|---|---|---|---|---|---|---|"]
    for ce in cases:
        ok = sum(s.correct for s in ce.scores)
        mark = {"exact": "", "alternate": " (alt)", "wrong": " ✗"}[ce.outcome_grade]
        L.append(f"| {ce.request_id} | {ce.payer} | {ce.gold.case_type} | {ce.gold.packet_outcome.value} | "
                 f"{ce.result.outcome.value}{mark} | {ok}/{len(ce.scores)} | {sum(s.false_met for s in ce.scores)} |")
    errored = [r for r in rows if "error" in r]
    if errored:
        L += ["", "Cases that errored: " + ", ".join(f"{r['id']} ({r['error'][:80]})" for r in errored)]
    return "\n".join(L) + "\n"


def qa_report(run_name: str, cases, m: dict, cfg: LLMConfig) -> str:
    from evals.qa import review

    by_id = {ce.request_id: ce for ce in cases}
    findings = []
    for f in m["failures"]:
        qa, rec = review(by_id[f["case"]], f["criterion"], cfg)
        findings.append((f, qa))
        print(f"  QA {f['case']} {f['criterion']}: {qa.verdict.value} / {qa.root_cause.value} -> {qa.fix_target.value}",
              flush=True)
    L = [f"# QA report: {run_name}", "",
         "This report comes from the QA agent in `evals/qa.py` (prompt `qa_review@v1`). It reviewed every disagreement between the "
         "agent and gold. It sees the gold label and the full chart, which the agent never does. It decides whether the agent or "
         "the gold label is wrong, then names a root cause and where the fix belongs. Its verdicts are a model's judgment: a "
         "human reads them before acting on them.", ""]
    if not findings:
        return "\n".join(L + ["No disagreements to review."]) + "\n"
    v = Counter(q.verdict.value for _, q in findings)
    rc = Counter(q.root_cause.value for _, q in findings)
    ft = Counter(q.fix_target.value for _, q in findings)
    L += [f"**{len(findings)} disagreements.** Verdicts: " + ", ".join(f"{k} {n}" for k, n in v.most_common()) + ".", "",
          "Root causes: " + ", ".join(f"{k} {n}" for k, n in rc.most_common()) + ".", "",
          "Where fixes belong: " + ", ".join(f"{k} {n}" for k, n in ft.most_common()) + ".", "",
          "## Findings", ""]
    for f, q in findings:
        L += [f"### {f['case']} ({f['payer']}) {f['criterion']} (policy {f['policy_ref']}): agent {f['agent']}, gold {f['gold']}",
              "",
              f"- Verdict: **{q.verdict.value}**. Root cause: {q.root_cause.value}. Fix target: {q.fix_target.value}.",
              f"- Planted state: `{f['state']}`. Retrieval surfaced the gold evidence: {f['retrieved_gold_evidence']}.",
              f"- {q.explanation}",
              f"- Suggested fix: {q.suggested_fix}", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report-only", metavar="RUN", help="report on an existing runs/<RUN> without running the agent")
    ap.add_argument("--qa", action="store_true", help="run the QA agent on every disagreement")
    ap.add_argument("--qa-model", help="model for the QA agent (default: PA_AGENT_MODEL)")
    ap.add_argument("--out-dir", default=str(ROOT / "docs"))
    ours, rest = ap.parse_known_args(argv)

    if ours.report_only:
        run_name = ours.report_only
    else:
        if "--run-name" not in rest:
            ap.error("pass --run-name so the report can find the run")
        run_name = rest[rest.index("--run-name") + 1]
        pipeline.main(rest)
    run_dir = pipeline.RUNS / run_name
    cases = load_run(run_dir)
    m = compute(cases, run_dir)
    out_dir = Path(ours.out_dir)
    notes_path = out_dir / "eval_notes" / f"{run_name}.md"
    notes = notes_path.read_text() if notes_path.exists() else None
    (out_dir / "EVAL_REPORT.md").write_text(eval_report(run_name, run_dir, m, cases, notes))
    print(f"wrote {out_dir / 'EVAL_REPORT.md'}")
    if ours.qa:
        cfg = LLMConfig()
        if ours.qa_model:
            cfg.model = ours.qa_model
        (out_dir / "QA_REPORT.md").write_text(qa_report(run_name, cases, m, cfg))
        print(f"wrote {out_dir / 'QA_REPORT.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
